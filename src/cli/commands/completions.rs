//! `tea completions`: print a shell completion script on stdout.
//!
//! The scripts are static: they are generated once here, so `tea completions`
//! stays deterministic and dependency-free. Every subcommand and option listed
//! by [`crate::cli::usage_text`] is covered.

use std::ffi::OsString;
use std::process::ExitCode;

use crate::cli::{CliError, CliResult};

/// Shells with a bundled completion script, in documentation order.
const SHELLS: [&str; 3] = ["bash", "zsh", "fish"];

fn supported_shells() -> String {
    SHELLS.join(", ")
}

fn usage_error(message: String) -> CliError {
    CliError::usage(format!(
        "{message}\nsupported shells: {}",
        supported_shells()
    ))
}

pub(crate) fn cmd_completions(args: &[OsString]) -> CliResult {
    let (shell, extra) = match args {
        [] => return Err(usage_error(String::from("tea: completions: missing shell"))),
        [shell, rest @ ..] => (shell.to_string_lossy(), rest.first()),
    };
    if let Some(extra) = extra {
        return Err(usage_error(format!(
            "tea: completions: unexpected argument '{}'",
            extra.to_string_lossy()
        )));
    }

    let script = match shell.as_ref() {
        "bash" => BASH,
        "zsh" => ZSH,
        "fish" => FISH,
        other => {
            return Err(usage_error(format!(
                "tea: completions: unsupported shell '{other}'"
            )))
        }
    };
    print!("{script}");
    Ok(ExitCode::SUCCESS)
}

const BASH: &str = r#"# bash completion for tea (generated by `tea completions bash`).
#
# Install:  tea completions bash > /etc/bash_completion.d/tea
#       or: source <(tea completions bash)
#
# commands: new init check run infuse steep brew flavors build test pytest fmt
#           lint clean install doctor gc repl add remove sync lock completions help
# options:  --json --color --no-color --verbose --quiet -o --output
#           --runtime-lib --no-cache --flavor --merge --show --force --check
#           --dry-run --no-echo --no-banner --target -c -i --help -h --version -V

_tea() {
    local cur prev commands options
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"
    commands="new init check run infuse steep brew flavors build test pytest fmt lint clean install doctor gc repl add remove sync lock completions help"
    options="--json --color --no-color --verbose --quiet --flavor --merge --show --no-echo --no-banner --help -h --version -V"

    case "$prev" in
        --color)
            COMPREPLY=( $(compgen -W "auto always never" -- "$cur") )
            return 0
            ;;
        -o|--output|--runtime-lib|--target)
            COMPREPLY=( $(compgen -f -- "$cur") )
            return 0
            ;;
        --flavor|--merge|--flavor=*|--merge=*)
            COMPREPLY=( $(compgen -f -- "$cur") )
            return 0
            ;;
    esac

    if [ "$COMP_CWORD" -eq 1 ]; then
        COMPREPLY=( $(compgen -W "$commands -c -i --help -h --version -V" -- "$cur") )
        return 0
    fi

    case "${COMP_WORDS[1]}" in
        completions)
            COMPREPLY=( $(compgen -W "bash zsh fish" -- "$cur") )
            return 0
            ;;
        help)
            COMPREPLY=( $(compgen -W "$commands" -- "$cur") )
            return 0
            ;;
        new|init)
            COMPREPLY=( $(compgen -W "--force" -- "$cur") )
            COMPREPLY+=( $(compgen -d -- "$cur") )
            return 0
            ;;
        build|brew)
            COMPREPLY=( $(compgen -W "$options -o --output --runtime-lib --no-cache --flavor" -- "$cur") )
            return 0
            ;;
        steep)
            COMPREPLY=( $(compgen -W "$options --flavor --merge --show" -- "$cur") )
            COMPREPLY+=( $(compgen -f -- "$cur") )
            return 0
            ;;
        flavors)
            COMPREPLY=( $(compgen -W "--verbose --quiet" -- "$cur") )
            return 0
            ;;
        run|infuse)
            COMPREPLY=( $(compgen -f -- "$cur") )
            return 0
            ;;
        fmt)
            COMPREPLY=( $(compgen -W "$options --check" -- "$cur") )
            return 0
            ;;
        clean)
            COMPREPLY=( $(compgen -W "--dry-run" -- "$cur") )
            return 0
            ;;
        install)
            COMPREPLY=( $(compgen -W "--target --verbose --quiet" -- "$cur") )
            COMPREPLY+=( $(compgen -f -- "$cur") )
            return 0
            ;;
        repl)
            COMPREPLY=( $(compgen -W "$options --no-echo --no-banner" -- "$cur") )
            return 0
            ;;
        doctor)
            COMPREPLY=( $(compgen -W "--json --no-color" -- "$cur") )
            return 0
            ;;
        add|remove|sync|lock)
            # all arguments are forwarded verbatim to uv
            return 0
            ;;
        pytest)
            COMPREPLY=( $(compgen -W "$options -q -x -k --maxfail" -- "$cur") )
            return 0
            ;;
    esac

    if [[ "$cur" == -* ]]; then
        COMPREPLY=( $(compgen -W "$options" -- "$cur") )
        return 0
    fi
    if [[ "$cur" != "" ]]; then
        COMPREPLY=( $(compgen -f -- "$cur") )
    fi
    return 0
}

complete -F _tea tea
"#;

